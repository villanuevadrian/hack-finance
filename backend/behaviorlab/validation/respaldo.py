from dataclasses import dataclass

import numpy as np

from behaviorlab.game import apply_decision, new_game
from behaviorlab.inference import estimate_posterior
from behaviorlab.inference.provisional import (
    ETA_GRID,
    LAMBDA_GRID,
    THETA_GRID,
    action_probabilities,
    log_likelihood_grid,
)
from behaviorlab.portfolio import DEFAULT_N_PATHS
from contracts import Action, Catalog, Decision, GameState, OnboardingAnswers, Scenario

PARAMS = ("lambda", "theta", "eta")
# V2 assumptions about self-report (documented, not measured): people declare more tolerance
STATED_BIAS = 0.08
STATED_NOISE = 0.08
# O4 bands of theta (sell_all, sell_part, wait, buy_more)
O4_BANDS = ((0.0, 0.10), (0.10, 0.20), (0.20, 0.35), (0.35, 1.0))
TRAIN_ROUNDS = 10


@dataclass(frozen=True)
class RecoveryRow:
    name: str
    mae: float
    coverage: float
    mean_width: float


@dataclass(frozen=True)
class RuleRow:
    threshold: float
    n_sold: int
    n: int
    theta_mean: float


@dataclass(frozen=True)
class PredictionRow:
    method: str
    lpd: float
    accuracy: float


def _play_model_player(
    answers: OnboardingAnswers, catalog: Catalog, seed: int, true: dict[str, float]
) -> tuple[Scenario, GameState]:
    """A full game where every action is sampled from the choice model with `true` params."""
    rng = np.random.default_rng([seed, 99])
    scenario, state = new_game(f"v1-{seed}", answers, catalog, seed)
    while not state.finished:
        probe = Decision(
            round_index=state.round_index,
            phase=state.phase,  # type: ignore[arg-type]
            kind=state.kind,  # type: ignore[arg-type]
            action=state.available_actions[0],
            available_actions=state.available_actions,
            response_time_ms=0,
            wealth_eur=state.wealth_eur,
            invested_eur=state.invested_eur,
            cash_eur=state.cash_eur,
            salary_eur=state.salary_eur,
            portfolio_drawdown=state.portfolio_drawdown,
            salary_raise_eur=state.salary_raise_eur,
        )
        probs = action_probabilities(probe, true["lambda"], true["theta"], true["eta"])
        actions = list(probs)
        choice = actions[int(rng.choice(len(actions), p=np.array(list(probs.values()))))]
        state = apply_decision(state, scenario, choice, 2_000)
    return scenario, state


def _true_params(rng: np.random.Generator) -> dict[str, float]:
    return {
        "lambda": float(rng.uniform(LAMBDA_GRID[0], LAMBDA_GRID[-1])),
        "theta": float(rng.uniform(THETA_GRID[0], THETA_GRID[-1])),
        "eta": float(rng.uniform(ETA_GRID[0], ETA_GRID[-1])),
    }


def v1_recovery(
    answers: OnboardingAnswers, catalog: Catalog, n_players: int = 200, seed: int = 2026
) -> list[RecoveryRow]:
    """MAE, coverage of the 90 % interval and mean width per parameter."""
    rng = np.random.default_rng(seed)
    errors: dict[str, list[float]] = {p: [] for p in PARAMS}
    inside: dict[str, list[bool]] = {p: [] for p in PARAMS}
    widths: dict[str, list[float]] = {p: [] for p in PARAMS}
    for i in range(n_players):
        true = _true_params(rng)
        _, state = _play_model_player(answers, catalog, seed + i, true)
        summary = {s.name: s for s in estimate_posterior(state.history).summary}
        for p in PARAMS:
            s = summary[p]
            errors[p].append(abs(s.mean - true[p]))
            inside[p].append(s.ci_low <= true[p] <= s.ci_high)
            widths[p].append(s.ci_high - s.ci_low)
    return [
        RecoveryRow(
            p, float(np.mean(errors[p])), float(np.mean(inside[p])), float(np.mean(widths[p]))
        )
        for p in PARAMS
    ]


def v1b_rule_players(
    answers: OnboardingAnswers,
    catalog: Catalog,
    thresholds: tuple[float, ...] = (0.05, 0.10, 0.15, 0.20, 0.30),
    n_seeds: int = 20,
) -> list[RuleRow]:
    """Players NOT generated by the model: sell all at a fixed drawdown, otherwise hold."""
    rows = []
    for thr in thresholds:
        thetas, sold = [], 0
        for seed in range(n_seeds):
            scenario, state = new_game("v1b", answers, catalog, seed)
            did_sell = False
            while not state.finished:
                av = state.available_actions
                if Action.SELL_ALL in av and state.portfolio_drawdown >= thr:
                    action, did_sell = Action.SELL_ALL, True
                else:
                    action = next(
                        a for a in (Action.HOLD, Action.STAY_OUT, Action.INVEST_RAISE_50) if a in av
                    )
                state = apply_decision(state, scenario, action, 2_000)
            sold += did_sell
            thetas.append(
                next(s.mean for s in estimate_posterior(state.history).summary if s.name == "theta")
            )
        rows.append(RuleRow(thr, sold, n_seeds, float(np.mean(thetas))))
    return rows


def _band_weights(band: tuple[float, float]) -> np.ndarray:
    """Uniform prior restricted to a theta band (questionnaire baseline)."""
    mask = (THETA_GRID >= band[0]) & (THETA_GRID < band[1])
    w = np.ones((len(LAMBDA_GRID), len(THETA_GRID), len(ETA_GRID)))
    w[:, ~mask, :] = 0
    return w / w.sum()


def _predict(weights: np.ndarray, decision: Decision) -> tuple[float, bool]:
    """log predictive probability of the decision and whether the mode equals it."""
    log_p = {
        a: log_likelihood_grid([decision.model_copy(update={"action": a})])
        for a in decision.available_actions
    }
    pred = {a: float((weights * np.exp(lp)).sum()) for a, lp in log_p.items()}
    return float(np.log(max(pred[decision.action], 1e-300))), max(
        pred, key=pred.get
    ) == decision.action


def v2_prediction(
    answers: OnboardingAnswers, catalog: Catalog, n_players: int = 200, seed: int = 7
) -> list[PredictionRow]:
    """Mean log predictive probability (higher is better) and accuracy on rounds 11-15."""
    rng = np.random.default_rng(seed)
    scores: dict[str, list[float]] = {"juego": [], "cuestionario": [], "azar": []}
    hits: dict[str, list[bool]] = {"juego": [], "cuestionario": [], "azar": []}
    for i in range(n_players):
        true = _true_params(rng)
        stated = float(np.clip(true["theta"] + STATED_BIAS + rng.normal(0, STATED_NOISE), 0, 0.999))
        band = next(b for b in O4_BANDS if b[0] <= stated < b[1])
        _, state = _play_model_player(answers, catalog, seed + 1000 + i, true)
        train = [d for d in state.history if d.round_index <= TRAIN_ROUNDS and not d.timed_out]
        test = [d for d in state.history if d.round_index > TRAIN_ROUNDS and not d.timed_out]
        log_l = log_likelihood_grid(train)
        game_w = np.exp(log_l - log_l.max())
        game_w /= game_w.sum()
        quiz_w = _band_weights(band)
        for d in test:
            lp, hit = _predict(game_w, d)
            scores["juego"].append(lp)
            hits["juego"].append(hit)
            lp, hit = _predict(quiz_w, d)
            scores["cuestionario"].append(lp)
            hits["cuestionario"].append(hit)
            k = len(d.available_actions)
            scores["azar"].append(float(np.log(1 / k)))
            hits["azar"].append(bool(rng.random() < 1 / k))
    return [PredictionRow(m, float(np.mean(scores[m])), float(np.mean(hits[m]))) for m in scores]


def v4_invariants(answers: OnboardingAnswers, catalog: Catalog) -> dict[str, float]:
    """Numerical checks reported as numbers (the unit tests assert them)."""
    _, state = new_game("v4", answers, catalog, 1)
    post = estimate_posterior(state.history)
    max_dev = max(abs(sum(w) - 1) for w in post.marginals.values())
    return {
        "max_desviacion_suma_pesos": max_dev,
        "error_estandar_max_p_panico": float(np.sqrt(0.25 / DEFAULT_N_PATHS)),
        "n_trayectorias": float(DEFAULT_N_PATHS),
    }
